"""The fix loop's memory and decisions.

- record_run: remembers findings across scan rounds so we can say what was
  fixed, what is new and what is still open.
- write_fix_tasks: an instruction file the coding agent reads to fix issues.
- write_summary: a plain-English summary of the whole session.
- decide: the Stop-hook state machine (pure function, easy to test)."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

from . import readiness
from .coverage import Coverage, gaps, is_complete, percent, to_markdown_table
from .findings import Finding, SEVERITIES, severity_rank
from .report import accepted_lines, report_skipped_first


def fid(f: Finding) -> str:
    return hashlib.sha1(f"{f.check}|{f.title}|{f.target}".encode()).hexdigest()[:12]


def _load(out: Path) -> dict:
    try:
        return json.loads((out / "history.json").read_text())
    except (OSError, ValueError):
        return {"runs": [], "session": {"seen": {}, "rounds": 0, "last_ids": []}, "last_clean": False}


def previous_skipped(out_dir: str) -> dict:
    """{name: reason} for the checks that were skipped on the previous scan, so the next report can list them
    first and say which of them ran this time."""
    return _load(Path(out_dir)).get("last_skipped", {})


def record_run(out_dir: str, findings: list[Finding], fail_on: str,
               coverage: list[Coverage] | None = None, accepted=None, notes: list[str] | None = None) -> dict:
    """`findings` are the ones still active; findings the owner accepted come separately in `accepted`."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    h = _load(out)
    if h.get("last_clean"):  # previous session finished clean: start a new one
        h["session"] = {"seen": {}, "rounds": 0, "last_ids": []}
        h["last_clean"] = False
    s = h["session"]
    tracked = [f for f in findings if f.severity != "info"]
    cur = {fid(f): f for f in tracked}
    prev_ids = set(s["last_ids"])
    for i, f in cur.items():
        s["seen"][i] = {"title": f.title, "severity": f.severity, "target": f.target, "fix": f.fix}
    s["rounds"] += 1
    s["last_ids"] = list(cur)
    blocking = [f for f in tracked if severity_rank(f.severity) >= severity_rank(fail_on)]
    if blocking:
        s["had_blocking"] = True
    h["last_clean"] = not blocking
    prev_skipped = h.get("last_skipped", {})
    h["last_skipped"] = {c.name: c.detail for c in (coverage or []) if c.status == "skipped"}
    h["runs"].append({"time": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                      "total": len(tracked), "blocking": len(blocking)})
    h["runs"] = h["runs"][-50:]
    (out / "history.json").write_text(json.dumps(h, indent=2))
    accepted = accepted or []
    accepted_ids = {fid(a.finding) for a in accepted}
    fixed = [dict(v, id=i) for i, v in s["seen"].items() if i not in cur and i not in accepted_ids]
    coverage = coverage or []
    return {
        "coverage": coverage,
        "coverage_percent": percent(coverage),
        "prev_skipped": prev_skipped,
        "complete": is_complete(coverage),
        "gaps": gaps(coverage),
        "accepted": accepted,
        "notes": notes or [],
        "clean": not blocking,
        "rounds": s["rounds"],
        "blocking": blocking,
        "open_other": [f for f in tracked if f not in blocking],
        "fixed": fixed,
        "new_this_round": [cur[i] for i in cur if i not in prev_ids and s["rounds"] > 1],
        "seen_total": len(s["seen"]),
        "had_blocking": bool(s.get("had_blocking")),
    }


def _line(f: Finding) -> str:
    where = f" ({f.target})" if f.target else ""
    return f"- [{f.severity.upper()}] {f.title}{where}"


def write_fix_tasks(out_dir: str, result: dict) -> Path:
    p = Path(out_dir) / "fix_tasks.md"
    lines = ["# Fix tasks (generated by guard)", "",
             "Instructions for the coding agent:",
             "1. Fix every BLOCKING item below in the source code, at the root cause.",
             "2. Do not edit guard, its config, or its scope to make findings disappear. "
             "Do not add ignore comments just to silence a finding.",
             "3. If an item is a false positive or a deliberate choice, do NOT suppress it. Say so in your final "
             "summary with the reason. Only the project owner may accept a risk, by adding an entry (check, title "
             "or target, reason, owner, optional expiry) to `accepted_risks` in guard.config.json; propose the "
             "entry to them instead of adding it yourself. Accepted risks stay visible in the reports.",
             "4. Never sign off a launch-readiness item yourself (`launch_signoffs`). Those are the owner's "
             "statements about things guard cannot check.",
             "5. When finished, stop. The check runs again automatically (or run `guard scan`).", ""]
    if not result["blocking"]:
        lines += ["No blocking issues. Nothing to fix.", ""]
    for n, f in enumerate(result["blocking"], 1):
        lines += [f"## {n}. [{f.severity.upper()}] {f.title}", f"- where: `{f.target or 'n/a'}`",
                  f"- problem: {f.detail}"]
        if f.evidence:
            lines.append(f"- evidence: `{f.evidence}`")
        if f.fix:
            lines.append(f"- suggested fix: {f.fix}")
        lines.append("")
    if result["open_other"]:
        lines += ["## Not blocking (for the owner to decide)", ""] + [_line(f) for f in result["open_other"]] + [""]
    if result.get("gaps"):
        lines += ["## Checks that did not run", ""] + [f"- {c.name}: {c.detail}" for c in result["gaps"]] + [""]
    lines += accepted_lines(result.get("accepted"))
    p.write_text("\n".join(lines))
    return p


def _status(result: dict, fail_on: str) -> str:
    if not result["clean"]:
        return f"NOT CLEAN. {len(result['blocking'])} issue(s) at or above '{fail_on}' still open."
    if result["complete"]:
        return f"CLEAN. No issues at or above '{fail_on}' remain."
    names = ", ".join(c.name for c in result["gaps"])
    return (f"NO BLOCKING ISSUES FOUND, BUT THIS IS NOT A FULL CLEAN. {len(result['gaps'])} check(s) did not run "
            f"({names}), so problems they would catch were not looked for. See the table below.")


def write_summary(out_dir: str, result: dict, fail_on: str) -> Path:
    p = Path(out_dir) / "summary.md"
    pct = result.get("coverage_percent")
    lines = ["# Security check summary", "", f"**Status:** {_status(result, fail_on)}",
             f"**Coverage:** {pct}% of applicable checks ran" if pct is not None else "**Coverage:** n/a",
             f"**Scan rounds in this session:** {result['rounds']}",
             f"**Issues found in total:** {result['seen_total']}", ""]
    lines += report_skipped_first(result.get("prev_skipped"), result.get("coverage", []))
    lines += to_markdown_table(result.get("coverage", []))
    if result["fixed"]:
        lines += [f"## Fixed ({len(result['fixed'])})"]
        lines += [f"- [{v['severity'].upper()}] {v['title']}" + (f" ({v['target']})" if v["target"] else "")
                  for v in result["fixed"]]
        lines.append("")
    if result["blocking"]:
        lines += [f"## Still open and blocking ({len(result['blocking'])})"] + [_line(f) for f in result["blocking"]] + [""]
    if result["open_other"]:
        lines += [f"## Left for you to decide ({len(result['open_other'])})",
                  "Below the failure threshold, so not auto-fixed:"] + [_line(f) for f in result["open_other"]] + [""]
    lines += accepted_lines(result.get("accepted"))
    lines += readiness.to_markdown(result.get("readiness") or readiness.items({}))
    if result.get("notes"):
        lines += ["## Notes"] + [f"- {n}" for n in result["notes"]] + [""]
    lines += ["## What this did not check",
              "- Whether your features work correctly for real users.",
              "- Business-logic flaws a scanner cannot see.",
              "- Anything not configured (live checks only cover the staging host and routes you listed).", ""]
    p.write_text("\n".join(lines))
    return p


def decide(blocking: int, state: dict, max_rounds: int, had_issues: bool) -> tuple[int, str, dict]:
    """Stop-hook decision. Returns (exit_code, message_kind, new_state).
    exit 2 = block the stop and send Claude back to work; exit 0 = allow stop."""
    if state.get("gave_up"):
        # Already told the user. Stay quiet until the issues are gone, then reset.
        return 0, "done", ({"gave_up": True} if blocking else {})
    if blocking:
        attempts = state.get("attempts", 0) + 1
        if attempts > max_rounds:
            return 2, "gave_up", {"gave_up": True}
        return 2, "fix", {"attempts": attempts}
    if had_issues and not state.get("summary_requested"):
        return 2, "summary", {"summary_requested": True}
    return 0, "done", {}
